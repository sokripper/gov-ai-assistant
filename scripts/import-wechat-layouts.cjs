/* Reproducible local import; no network, no source library mutation. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const source=process.argv[2];
if(!source)throw Error('Usage: node scripts/import-wechat-layouts.cjs <pure-layout-library>');
const manifest=JSON.parse(fs.readFileSync(path.join(source,'manifest.json'),'utf8'));
const templates=manifest.templates.map(t=>{
  if(!/^\d{2}$/.test(t.id))throw Error('Invalid template ID');
  const html=fs.readFileSync(path.join(source,'templates',t.id,'article.html'),'utf8');
  if(/<script\b|\son\w+\s*=|<iframe\b/i.test(html))throw Error('Unexpected executable content');
  return {...t,html,sha256:crypto.createHash('sha256').update(html).digest('hex')};
});
const output=path.join(__dirname,'../docs/prototypes/wechat-layout-library.js');
fs.writeFileSync(output,'/* Generated by import-wechat-layouts.cjs from user-provided local layout library. */\nwindow.WX_LAYOUT_LIBRARY = '+JSON.stringify({title:manifest.title,scope:manifest.scope,templates}).replace(/</g,'\\u003c')+';\n');
console.log('Imported '+templates.length+' complete HTML layouts; source hashes retained.');
